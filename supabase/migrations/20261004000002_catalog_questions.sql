-- ============================================================================
-- 0002 · Learning catalog & question bank
-- Subjects/topics follow the BPSC BCS preliminary syllabus (200 marks).
-- Every question carries its SOURCE (previous exam, book, newspaper, AI …).
-- The bank is NOT fixed: the daily AI pipeline appends current-affairs
-- questions every day, admins add/import more, and questions built on facts
-- that later change are archived automatically (see 0005 · facts).
-- Correct answers are hidden from clients via column privileges and are only
-- revealed through security-definer RPCs after the user has answered.
-- ============================================================================

