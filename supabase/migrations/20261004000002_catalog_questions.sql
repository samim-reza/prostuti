-- ---------------------------------------------------------------------------
-- Public question payload (never includes the answer).
-- ---------------------------------------------------------------------------
create or replace function public.question_public_json(q public.questions)
returns jsonb
language sql immutable
set search_path = ''
as $$
  select jsonb_build_object(
    'id', q.id, 'subject_id', q.subject_id, 'topic_id', q.topic_id, 'stem', q.stem,
    'options', q.options, 'difficulty', q.difficulty, 'language', q.language,
    'source_ref', q.source_ref, 'source_url', q.source_url, 'year', q.year);
$$;

-- Browse/practice questions (keyset pagination by id).
create or replace function public.get_practice_questions(
  p_subject smallint default null, p_topic int default null, p_source bigint default null,
  p_limit int default 20, p_after_id bigint default null, p_unseen_only boolean default false,
  p_search text default null
)
returns jsonb
language sql stable security definer
set search_path = ''
as $$
  select coalesce(jsonb_agg(public.question_public_json(q) order by q.id), '[]'::jsonb)
    from (
      select q.* from public.questions q
       where q.status = 'published'
         and (p_subject is null or q.subject_id = p_subject)
         and (p_topic is null or q.topic_id = p_topic)
         and (p_source is null or q.source_id = p_source)
         and (p_after_id is null or q.id > p_after_id)
         and (p_search is null or q.stem ilike '%' || p_search || '%')
         and (not p_unseen_only or not exists (
               select 1 from public.question_attempts a
                where a.user_id = auth.uid() and a.question_id = q.id))
         -- never leak today's live daily-exam questions into practice
         and not exists (
               select 1 from public.daily_exams d
                where d.exam_date = public.bd_today() and q.id = any (d.question_ids))
       order by q.id
       limit least(coalesce(p_limit, 20), 50)
    ) q;
$$;

-- True when the question is part of today's daily exam and the caller has not
-- submitted it yet — answers must stay hidden in that case.
create or replace function public.is_live_daily_question(p_question bigint)
returns boolean
language sql stable security definer
set search_path = ''
as $$
  select exists (
    select 1 from public.daily_exams d
     where d.exam_date = public.bd_today()
       and p_question = any (d.question_ids)
       and not exists (
         select 1 from public.exam_sessions s
          where s.user_id = auth.uid() and s.daily_exam_id = d.id and s.status = 'submitted'));
$$;

create or replace function public.answer_practice_question(p_question bigint, p_selected smallint)
returns jsonb
language plpgsql security definer
set search_path = ''
as $$
declare
  v_uid uuid := auth.uid();
  v_q   public.questions;
  v_ok  boolean;
begin
  if v_uid is null then raise exception 'not_authenticated' using errcode = 'PT401'; end if;
  perform public.enforce_rate_limit('practice_answer', 300, 3600);
  if public.is_live_daily_question(p_question) then
    raise exception 'question_locked' using errcode = 'PT403';
  end if;

  select * into v_q from public.questions where id = p_question and status = 'published';
  if not found then raise exception 'question_not_found' using errcode = 'PT404'; end if;

  v_ok := (p_selected = v_q.correct_index);
  insert into public.question_attempts (user_id, question_id, selected_index, is_correct, mode)
  values (v_uid, p_question, p_selected, v_ok, 'practice');
  update public.questions
     set times_answered = times_answered + 1,
         times_correct  = times_correct + case when v_ok then 1 else 0 end
   where id = p_question;
  perform public.update_mastery(v_uid, v_q.topic_id, v_ok, 0.15);
  perform public.touch_streak(v_uid);

  return jsonb_build_object('is_correct', v_ok, 'correct_index', v_q.correct_index,
                            'explanation', v_q.explanation);
end $$;

create or replace function public.reveal_answer(p_question bigint)
returns jsonb
language plpgsql security definer
set search_path = ''
as $$
declare
  v_uid uuid := auth.uid();
  v_q   public.questions;
begin
  if v_uid is null then raise exception 'not_authenticated' using errcode = 'PT401'; end if;
  perform public.enforce_rate_limit('reveal_answer', 600, 3600);
  if public.is_live_daily_question(p_question) then
    raise exception 'question_locked' using errcode = 'PT403';
  end if;
  select * into v_q from public.questions where id = p_question and status = 'published';
  if not found then raise exception 'question_not_found' using errcode = 'PT404'; end if;
  insert into public.question_attempts (user_id, question_id, mode) values (v_uid, p_question, 'reveal');
  return jsonb_build_object('correct_index', v_q.correct_index, 'explanation', v_q.explanation);
end $$;

-- "ভুলের খাতা": questions whose latest graded attempt was wrong.
create or replace function public.get_wrong_answers(
  p_limit int default 20, p_before timestamptz default null, p_subject smallint default null
)
returns jsonb
language sql stable security definer
set search_path = ''
as $$
  with latest as (
    select distinct on (a.question_id) a.question_id, a.selected_index, a.is_correct, a.created_at
      from public.question_attempts a
     where a.user_id = auth.uid() and a.mode in ('exam', 'practice')
     order by a.question_id, a.created_at desc
  )
  select coalesce(jsonb_agg(
           public.question_public_json(q) || jsonb_build_object(
             'correct_index', q.correct_index, 'explanation', q.explanation,
             'selected_index', l.selected_index, 'attempted_at', l.created_at)
           order by l.created_at desc), '[]'::jsonb)
    from (select * from latest
           where is_correct = false and (p_before is null or created_at < p_before)
           order by created_at desc
           limit least(coalesce(p_limit, 20), 50)) l
    join public.questions q on q.id = l.question_id
   where p_subject is null or q.subject_id = p_subject;
$$;

-- Previous-exam sources with question counts (for "বিগত বছরের প্রশ্ন").
create or replace function public.get_question_sources(p_kind public.source_kind default null)
returns jsonb
language sql stable security definer
set search_path = ''
as $$
  select coalesce(jsonb_agg(jsonb_build_object(
           'id', s.id, 'kind', s.kind, 'name', s.name, 'exam_type', s.exam_type, 'year', s.year,
           'publisher', s.publisher, 'url', s.url, 'question_count', c.cnt)
         order by s.year desc nulls last, s.name), '[]'::jsonb)
    from public.sources s
    join lateral (select count(*) as cnt from public.questions q
                   where q.source_id = s.id and q.status = 'published') c on true
   where (p_kind is null or s.kind = p_kind) and c.cnt > 0;
$$;

-- Subject list with question counts + the caller's mastery (one round trip).
create or replace function public.get_subjects_overview()
returns jsonb
language sql stable security definer
set search_path = ''
as $$
  select coalesce(jsonb_agg(jsonb_build_object(
           'id', s.id, 'code', s.code, 'name_bn', s.name_bn, 'name_en', s.name_en,
           'bcs_marks', s.bcs_marks, 'icon', s.icon, 'color', s.color,
           'question_count', (select count(*) from public.questions q where q.subject_id = s.id and q.status = 'published'),
           'mastery', (select round(avg(m.mastery)::numeric, 3) from public.user_topic_mastery m
                         join public.topics t on t.id = m.topic_id
                        where m.user_id = auth.uid() and t.subject_id = s.id),
           'topics', (select coalesce(jsonb_agg(jsonb_build_object(
                         'id', t.id, 'code', t.code, 'name_bn', t.name_bn, 'name_en', t.name_en,
                         'mastery', (select m.mastery from public.user_topic_mastery m
                                      where m.user_id = auth.uid() and m.topic_id = t.id))
                       order by t.sort), '[]'::jsonb)
                        from public.topics t where t.subject_id = s.id))
         order by s.sort), '[]'::jsonb)
    from public.subjects s;
$$;
