-- ---------------------------------------------------------------------------
-- Questions
-- ---------------------------------------------------------------------------
create table public.questions (
  id              bigint generated always as identity primary key,
  subject_id      smallint not null references public.subjects (id),
  topic_id        int references public.topics (id),
  stem            text not null check (char_length(stem) between 3 and 2000),
  options         jsonb not null check (jsonb_typeof(options) = 'array' and jsonb_array_length(options) between 2 and 5),
  correct_index   smallint not null,
  explanation     text,
  difficulty      smallint not null default 2 check (difficulty between 1 and 5),
  language        text not null default 'bn' check (language in ('bn', 'en')),
  source_id       bigint references public.sources (id) on delete set null,
  source_ref      text,
  source_url      text,
  exam_tags       text[] not null default '{}',
  year            int,
  status          text not null default 'published' check (status in ('draft', 'published', 'rejected', 'archived')),
  review_status   text not null default 'unverified' check (review_status in ('unverified', 'verified', 'flagged')),
  stem_hash       text generated always as (md5(lower(regexp_replace(stem, '\s+', '', 'g')))) stored,
  embedding       extensions.vector(1536),
  times_answered  int not null default 0,
  times_correct   int not null default 0,
  created_by      uuid references public.profiles (id) on delete set null,
  created_at      timestamptz not null default now(),
  constraint questions_correct_in_range check (correct_index >= 0 and correct_index < jsonb_array_length(options)),
  constraint questions_stem_unique unique (stem_hash)
);
create index questions_subject_topic_idx on public.questions (subject_id, topic_id, id) where status = 'published';
create index questions_source_idx        on public.questions (source_id, id);
create index questions_tags_idx          on public.questions using gin (exam_tags);
create index questions_stem_trgm         on public.questions using gin (stem extensions.gin_trgm_ops);
create index questions_embedding_hnsw    on public.questions using hnsw (embedding extensions.vector_cosine_ops);

-- Questions without an explicit topic fall into their subject's "general" topic,
-- so mastery tracking always has a topic to attribute to.
create or replace function public.questions_default_topic()
returns trigger
language plpgsql
set search_path = ''
as $$
begin
  if new.topic_id is null then
    select t.id into new.topic_id from public.topics t
     where t.subject_id = new.subject_id and t.is_general limit 1;
  end if;
  return new;
end $$;
create trigger questions_default_topic before insert or update of subject_id, topic_id on public.questions
  for each row execute function public.questions_default_topic();

alter table public.questions enable row level security;
create policy "questions: published readable" on public.questions for select to authenticated
  using (status = 'published' or public.is_staff());
create policy "questions: staff writes" on public.questions for all to authenticated
  using (public.is_staff()) with check (public.is_staff());

-- Hide answers + embeddings: clients must select explicit columns.
revoke all on public.questions from anon, authenticated;
grant select (id, subject_id, topic_id, stem, options, difficulty, language, source_id,
              source_ref, source_url, exam_tags, year, status, times_answered, times_correct, created_at)
  on public.questions to authenticated;

-- Every answer a user gives (exam, practice, or "show answer").
