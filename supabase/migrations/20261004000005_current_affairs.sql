-- When a fact is superseded/retracted, archive every question built on it so
-- learners never practise an outdated answer.
create or replace function public.facts_after_status_change()
returns trigger
language plpgsql security definer
set search_path = ''
as $$
begin
  if new.status <> 'active' and old.status = 'active' then
    update public.questions set status = 'archived'
     where fact_id = new.id and status = 'published';
  end if;
  return new;
end $$;
create trigger facts_after_status_change after update of status on public.facts
  for each row execute function public.facts_after_status_change();

