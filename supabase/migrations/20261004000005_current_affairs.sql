  user_id    uuid not null references public.profiles (id) on delete cascade,
  note_date  date not null,
  method     text not null check (method in ('ad', 'addon')),
  created_at timestamptz not null default now(),
  primary key (user_id, note_date, method)
);
alter table public.note_downloads enable row level security;
create policy "note_downloads: owner reads" on public.note_downloads for select to authenticated
  using (user_id = (select auth.uid()));
revoke insert, update, delete on public.note_downloads from anon, authenticated;

-- Called by the app after a rewarded ad completes (or for ad-free users).
create or replace function public.claim_note_download(p_method text default 'ad')
returns jsonb
language plpgsql security definer
set search_path = ''
as $$
declare v_uid uuid := auth.uid();
begin
  if v_uid is null then raise exception 'not_authenticated' using errcode = 'PT401'; end if;
  if p_method not in ('ad', 'addon') then raise exception 'invalid_method'; end if;
  if p_method = 'addon' and not public.user_has_feature(v_uid, 'ad_free') then
    raise exception 'feature_locked' using errcode = 'PT402', detail = 'ad_free';
  end if;
  perform public.enforce_rate_limit('note_download', 20, 0);
  if not exists (select 1 from public.daily_notes where note_date = public.bd_today() and status = 'published') then
    raise exception 'no_notes_today' using errcode = 'PT404';
  end if;
  insert into public.note_downloads (user_id, note_date, method) values (v_uid, public.bd_today(), p_method)
  on conflict do nothing;
  return jsonb_build_object('allowed', true, 'note_date', public.bd_today());
end $$;

