-- ============================================================================
-- 0005 · Current affairs (সাম্প্রতিক): news → facts → daily notes → daily exam
--
-- Pipeline (Edge Functions, scheduled by pg_cron — see 0009):
--   ingest-news          RSS from BD + international outlets → news_articles
--   generate-daily-notes AI extracts exam-relevant FACTS, de-duplicates them
--                        semantically against the permanent `facts` store,
--                        detects facts that SUPERSEDE older ones, and writes
--                        the day's notes
--   generate-daily-exam  MCQs from today's facts → questions (kept forever)
--
-- Notes are visible ONLY on their own Bangladesh calendar day (RLS), yet stay
-- in the database forever. Facts and their questions keep growing every day;
-- a superseded fact archives the questions built on it.
-- ============================================================================

