-- Notes of today, in one round trip, with download state for the caller.
create or replace function public.get_today_notes()
returns jsonb
language sql stable security invoker
set search_path = ''
as $$
  select jsonb_build_object(
    'note_date', public.bd_today(),
    'notes', coalesce((select jsonb_agg(jsonb_build_object(
                'id', n.id, 'category', n.category, 'title', n.title, 'summary', n.summary,
                'key_facts', n.key_facts, 'probable_questions', n.probable_questions,
                'importance', n.importance, 'source_links', n.source_links, 'created_at', n.created_at)
              order by n.importance desc, n.id)
              from public.daily_notes n
             where n.note_date = public.bd_today() and n.status = 'published'), '[]'::jsonb),
    'downloaded', exists (select 1 from public.note_downloads d
                           where d.user_id = auth.uid() and d.note_date = public.bd_today()),
    'daily_exam', (select jsonb_build_object('id', e.id, 'title_bn', e.title_bn,
                          'question_count', cardinality(e.question_ids),
                          'duration_minutes', e.duration_minutes)
                     from public.daily_exams e
                    where e.exam_date = public.bd_today() and e.status = 'published'));
$$;

-- Admin/pipeline helper: nearest active facts to an embedding.
create or replace function public.match_facts(
  p_embedding extensions.vector, p_threshold real default 0.85, p_limit int default 5
)
returns table (id bigint, fact text, entity text, category text, first_seen_date date, similarity real)
language sql stable security definer
set search_path = ''
as $$
  select f.id, f.fact, f.entity, f.category, f.first_seen_date,
         (1 - (f.embedding operator(extensions.<=>) p_embedding))::real
    from public.facts f
   where f.status = 'active' and f.embedding is not null
     and 1 - (f.embedding operator(extensions.<=>) p_embedding) >= p_threshold
   order by f.embedding operator(extensions.<=>) p_embedding
   limit p_limit;
$$;
revoke execute on function public.match_facts(extensions.vector, real, int) from public, anon, authenticated;

create or replace function public.match_questions(
  p_embedding extensions.vector, p_threshold real default 0.9, p_limit int default 5
)
returns table (id bigint, stem text, similarity real)
language sql stable security definer
set search_path = ''
as $$
  select q.id, q.stem, (1 - (q.embedding operator(extensions.<=>) p_embedding))::real
    from public.questions q
   where q.embedding is not null and q.status in ('published', 'draft')
     and 1 - (q.embedding operator(extensions.<=>) p_embedding) >= p_threshold
   order by q.embedding operator(extensions.<=>) p_embedding
   limit p_limit;
$$;
revoke execute on function public.match_questions(extensions.vector, real, int) from public, anon, authenticated;
